import { useEffect, useState } from 'react'
import { FiMinusCircle, FiPlusCircle, FiZap } from 'react-icons/fi'
import { getAiStatus } from '../../services/ai'
import { fetchReviewSummary } from '../../services/reviews'
import { isAbortError } from '../../services/http'
import { formatDate, pluralize } from '../../utils/format'
import './ReviewSummary.css'

/**
 * Gemini's summary of a product's reviews, written on the server and cached until the
 * reviews change. It is a nice extra rather than part of the page: when there are no
 * reviews it is left out, and when the AI cannot answer (no key, busy, too slow) a quiet
 * line says so and the reviews themselves carry on as normal.
 */
function ReviewSummary({ productId, revision = 0 }) {
  const [state, setState] = useState({ status: 'loading', summary: null, productId })

  useEffect(() => {
    const controller = new AbortController()
    // A summary being refreshed after a review change stays on screen until the new one
    // arrives; another product's summary never does.
    setState((current) => ({
      status: 'loading',
      summary: current.productId === productId ? current.summary : null,
      productId
    }))

    // Without a Gemini key on the server the summary request could only fail (and show
    // as an error in the browser console), so the quiet line is shown straight away.
    // getAiStatus is cached and shared with the assistant.
    getAiStatus()
      .then((enabled) => {
        if (controller.signal.aborted) return undefined
        if (enabled === false) {
          setState({ status: 'unavailable', summary: null, productId })
          return undefined
        }
        return fetchReviewSummary(productId, { signal: controller.signal }).then((summary) =>
          setState({ status: summary ? 'ready' : 'none', summary, productId })
        )
      })
      .catch((error) => {
        if (isAbortError(error)) return
        setState({ status: 'unavailable', summary: null, productId })
      })

    return () => controller.abort()
  }, [productId, revision])

  const { status, summary } = state

  if (status === 'none') return null

  if (status === 'unavailable') {
    return (
      <p className="review-summary-unavailable">
        <FiZap aria-hidden="true" />
        The AI summary of these reviews is not available right now. The reviews below are all
        here to read.
      </p>
    )
  }

  if (!summary) {
    return (
      <div className="review-summary card is-loading" role="status">
        <div className="skeleton review-summary-line" />
        <div className="skeleton review-summary-line is-short" />
        <span className="visually-hidden">Summarising the reviews</span>
      </div>
    )
  }

  return (
    <section className="review-summary card" aria-labelledby="review-summary-heading" aria-busy={status === 'loading'}>
      <div className="review-summary-head">
        <h3 id="review-summary-heading">What shoppers say</h3>
        <span className="badge badge-primary review-summary-badge">
          <FiZap aria-hidden="true" />
          AI summary
        </span>
      </div>

      <p className="review-summary-verdict">{summary.verdict}</p>

      {summary.pros.length || summary.cons.length ? (
        <div className="review-summary-points">
          {summary.pros.length ? (
            <div>
              <h4>Liked</h4>
              <ul>
                {summary.pros.map((point) => (
                  <li key={point}>
                    <FiPlusCircle aria-hidden="true" className="is-pro" />
                    {point}
                  </li>
                ))}
              </ul>
            </div>
          ) : null}
          {summary.cons.length ? (
            <div>
              <h4>Not so keen</h4>
              <ul>
                {summary.cons.map((point) => (
                  <li key={point}>
                    <FiMinusCircle aria-hidden="true" className="is-con" />
                    {point}
                  </li>
                ))}
              </ul>
            </div>
          ) : null}
        </div>
      ) : null}

      <p className="review-summary-note">
        Generated by Google Gemini from {pluralize(summary.basedOn, 'review')} on{' '}
        {formatDate(summary.generatedAt)}. AI can get things wrong, so read the reviews too.
      </p>
    </section>
  )
}

export default ReviewSummary
