import { fireEvent, screen, waitFor, within } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import ProductDetails from '../../pages/ProductDetails'
import { setToken } from '../../services/http'
import { fakeApi, fakeToken } from '../../test/fakeApi'
import { apiProduct, renderShopPage, shopper } from '../../test/renderShopPage'

const token = fakeToken(Math.floor(Date.now() / 1000) + 3600)

const imported = [
  { _id: 'r1', product: 1, user: null, reviewerName: 'Eleanor Collins', rating: 5, comment: 'Highly impressed!', verifiedPurchase: false, createdAt: '2025-04-30T09:41:02.053Z', updatedAt: '2025-04-30T09:41:02.053Z' },
  { _id: 'r2', product: 1, user: null, reviewerName: 'Lucas Gordon', rating: 4, comment: 'Very satisfied!', verifiedPurchase: true, createdAt: '2025-04-29T09:41:02.053Z', updatedAt: '2025-04-29T09:41:02.053Z' },
  { _id: 'r3', product: 1, user: null, reviewerName: 'Eleanor Moore', rating: 3, comment: 'Fine.', verifiedPurchase: false, createdAt: '2025-04-28T09:41:02.053Z', updatedAt: '2025-04-28T09:41:02.053Z' }
]

const baseStats = { rating: 4, reviewCount: 3, breakdown: { 1: 0, 2: 0, 3: 1, 4: 1, 5: 1 } }

const summary = {
  verdict: 'Shoppers like how long it lasts, though a few found it clumps.',
  pros: ['Long lasting'],
  cons: ['Can clump'],
  basedOn: 3,
  generatedAt: '2026-11-16T21:50:02.114Z'
}

function myOwn(overrides = {}) {
  return {
    _id: 'mine',
    product: 1,
    user: shopper._id,
    reviewerName: shopper.name,
    rating: 4,
    comment: 'Lovely, lasts all day',
    verifiedPurchase: false,
    createdAt: '2026-11-17T10:00:00.000Z',
    updatedAt: '2026-11-17T10:00:00.000Z',
    ...overrides
  }
}

function productRoutes(extra) {
  return {
    'GET /auth/me': () => [200, { success: true, user: shopper }],
    'GET /products': () => [200, { success: true, products: [apiProduct(1, { rating: 4, reviewCount: 3 })] }],
    'GET /lists': () => [200, { success: true, cart: [], wishlist: [], recentlyViewed: [] }],
    'PUT /lists/viewed': ({ body }) => [200, { success: true, recentlyViewed: body.ids }],
    'GET /products/1/price-history': () => [
      200,
      { success: true, productId: 1, currentPrice: 10, points: [], prediction: { hasEnoughData: false } }
    ],
    'GET /products/1/review-summary': () => [200, { success: true, summary, cached: true }],
    'GET /products/1/reviews': () => [
      200,
      { success: true, reviews: imported, pagination: { page: 1, limit: 5, total: 3, pages: 1 }, stats: baseStats, myReview: null }
    ],
    ...extra
  }
}

function renderProduct() {
  return renderShopPage(<ProductDetails />, { path: '/product/:id', url: '/product/1' })
}

describe('Product reviews', () => {
  // The product page scrolls to the top when it opens, which jsdom does not implement.
  beforeEach(() => vi.stubGlobal('scrollTo', vi.fn()))

  it('shows the reviews, the star breakdown and the AI summary to a guest', async () => {
    fakeApi(productRoutes())
    renderProduct()

    expect(await screen.findByText('Highly impressed!')).toBeInTheDocument()
    expect(screen.getByRole('list', { name: 'Reviews by star rating' })).toHaveTextContent('5 stars: 1 review')
    expect(within(screen.getByText('Very satisfied!').closest('li')).getByText('Verified purchase')).toBeInTheDocument()
    expect(screen.getByText('Showing 3 of 3 reviews')).toBeInTheDocument()

    const card = await screen.findByRole('region', { name: 'What shoppers say' })
    expect(within(card).getByText('AI summary')).toBeInTheDocument()
    expect(within(card).getByText(summary.verdict)).toBeInTheDocument()
    expect(within(card).getByText(/Generated by Google Gemini from 3 reviews/)).toBeInTheDocument()

    expect(screen.getByRole('link', { name: 'Sign in to write a review' })).toHaveAttribute('href', '/login')
  })

  it('keeps the page calm when the AI summary is not available', async () => {
    fakeApi(
      productRoutes({
        'GET /products/1/review-summary': () => [
          503,
          { success: false, message: 'The AI assistant is not set up on this server.', code: 'AI_UNAVAILABLE' }
        ]
      })
    )
    renderProduct()

    expect(await screen.findByText(/The AI summary of these reviews is not available right now/)).toBeInTheDocument()
    expect(screen.queryByRole('region', { name: 'What shoppers say' })).not.toBeInTheDocument()
    expect(screen.getByText('Highly impressed!')).toBeInTheDocument()
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  })

  describe('signed in', () => {
    beforeEach(() => {
      setToken(token)
      window.localStorage.setItem('shopsmart:lists-owner', JSON.stringify(shopper._id))
    })

    it('writes a review, checks it first and updates the rating on the page', async () => {
      const api = fakeApi(
        productRoutes({
          'POST /products/1/reviews': ({ body }) => [
            201,
            {
              success: true,
              review: myOwn({ rating: body.rating, comment: body.comment }),
              stats: { rating: 4.25, reviewCount: 4, breakdown: { 1: 0, 2: 0, 3: 1, 4: 2, 5: 1 } }
            }
          ]
        })
      )
      renderProduct()

      fireEvent.click(await screen.findByRole('button', { name: 'Write a review' }))
      const heading = screen.getByRole('heading', { name: 'Write a review' })
      await waitFor(() => expect(heading).toHaveFocus())

      fireEvent.click(screen.getByRole('button', { name: 'Post review' }))
      expect(await screen.findByText('Choose a rating from 1 to 5 stars')).toBeInTheDocument()
      expect(api.callsTo('POST /products/1/reviews')).toHaveLength(0)

      fireEvent.click(screen.getByRole('radio', { name: '4 stars, Very good' }))
      fireEvent.change(screen.getByLabelText('Your review'), { target: { value: '  Lovely, lasts all day  ' } })
      const summaryReads = api.callsTo('GET /products/1/review-summary').length
      fireEvent.click(screen.getByRole('button', { name: 'Post review' }))

      expect(await screen.findByText('Thanks, your review is posted.')).toBeInTheDocument()
      expect(api.callsTo('POST /products/1/reviews')[0].body).toEqual({ rating: 4, comment: 'Lovely, lasts all day' })
      await waitFor(() => expect(screen.getByRole('heading', { name: 'Your review' })).toHaveFocus())
      // The rating at the top of the page follows the new figures straight away.
      expect(screen.getByRole('link', { name: '4 reviews' })).toBeInTheDocument()
      expect(screen.getByText('Showing 4 of 4 reviews')).toBeInTheDocument()
      expect(screen.getByText('You')).toHaveClass('badge')
      // The summary is asked for again, because the reviews it read have changed.
      await waitFor(() => expect(api.callsTo('GET /products/1/review-summary')).toHaveLength(summaryReads + 1))
    })

    it('edits and deletes the shopper review after asking first', async () => {
      let mine = myOwn()
      const api = fakeApi(
        productRoutes({
          'GET /products/1/reviews': () => [
            200,
            {
              success: true,
              reviews: [mine, ...imported],
              pagination: { page: 1, limit: 5, total: 4, pages: 1 },
              stats: { rating: 4, reviewCount: 4, breakdown: { 1: 0, 2: 0, 3: 1, 4: 2, 5: 1 } },
              myReview: mine
            }
          ],
          'POST /products/1/reviews': ({ body }) => {
            mine = myOwn({ rating: body.rating, comment: body.comment })
            return [200, { success: true, review: mine, stats: { rating: 4.25, reviewCount: 4, breakdown: { 1: 0, 2: 0, 3: 1, 4: 1, 5: 2 } } }]
          },
          'DELETE /products/1/reviews/mine': () => [200, { success: true, message: 'Review deleted', stats: baseStats }]
        })
      )
      renderProduct()

      fireEvent.click(await screen.findByRole('button', { name: 'Edit your review' }))
      expect(screen.getByLabelText('Your review')).toHaveValue('Lovely, lasts all day')
      expect(screen.getByRole('radio', { name: '4 stars, Very good' })).toBeChecked()
      fireEvent.click(screen.getByRole('radio', { name: '5 stars, Excellent' }))
      fireEvent.click(screen.getByRole('button', { name: 'Save changes' }))

      expect(await screen.findByText('Your review is updated.')).toBeInTheDocument()
      expect(api.callsTo('POST /products/1/reviews')[0].body.rating).toBe(5)

      fireEvent.click(screen.getByRole('button', { name: 'Delete your review' }))
      expect(screen.getByText('Delete your review? This cannot be undone.')).toBeInTheDocument()
      expect(api.callsTo('DELETE /products/1/reviews/mine')).toHaveLength(0)
      fireEvent.click(screen.getByRole('button', { name: 'Yes, delete it' }))

      expect(await screen.findByText('Your review is deleted.')).toBeInTheDocument()
      await waitFor(() => expect(screen.getByRole('button', { name: 'Write a review' })).toHaveFocus())
      expect(screen.getByRole('link', { name: '3 reviews' })).toBeInTheDocument()
      expect(screen.queryByText('Lovely, lasts all day')).not.toBeInTheDocument()
    })

    it('shows the server message on the field it belongs to', async () => {
      fakeApi(
        productRoutes({
          'POST /products/1/reviews': () => [
            400,
            {
              success: false,
              message: 'Please check the highlighted fields',
              code: 'VALIDATION_ERROR',
              errors: [{ field: 'comment', message: 'Comment must be at least 3 characters' }]
            }
          ]
        })
      )
      renderProduct()

      fireEvent.click(await screen.findByRole('button', { name: 'Write a review' }))
      fireEvent.click(screen.getByRole('radio', { name: '2 stars, Fair' }))
      fireEvent.change(screen.getByLabelText('Your review'), { target: { value: 'Meh, ok' } })
      fireEvent.click(screen.getByRole('button', { name: 'Post review' }))

      expect(await screen.findByText('Comment must be at least 3 characters')).toBeInTheDocument()
      await waitFor(() => expect(screen.getByLabelText('Your review')).toHaveFocus())
    })
  })

  it('loads more reviews a page at a time and retries a failed list', async () => {
    let fail = true
    const many = Array.from({ length: 7 }, (_, index) => ({ ...imported[0], _id: `r${index}`, comment: `Review number ${index}` }))
    fakeApi(
      productRoutes({
        'GET /products/1/reviews': ({ url }) => {
          if (fail) return [500, { success: false, message: 'Something went wrong on our side.', code: 'SERVER_ERROR' }]
          const page = Number(new URL(url, 'http://localhost').searchParams.get('page'))
          const slice = many.slice((page - 1) * 5, page * 5)
          return [200, { success: true, reviews: slice, pagination: { page, limit: 5, total: 7, pages: 2 }, stats: baseStats, myReview: null }]
        }
      })
    )
    renderProduct()

    expect(await screen.findByRole('alert')).toHaveTextContent('We could not load the reviews.')
    fail = false
    fireEvent.click(screen.getByRole('button', { name: 'Try again' }))

    expect(await screen.findByText('Showing 5 of 7 reviews')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Show more reviews' }))
    expect(await screen.findByText('Showing 7 of 7 reviews')).toBeInTheDocument()
    expect(screen.getByText('Review number 6')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Show more reviews' })).not.toBeInTheDocument()
  })
})
